export function nativeSigningText(language, key) {
    return (language === 'vi' ? copy.vi : copy.en)[key] || copy.en[key] || key;
}

export function nativeSigningFieldLabel(language, field) {
    const key = typeof field === 'string' ? field : field?.key;
    return (language === 'vi' ? fieldLabels.vi : fieldLabels.en)[key]
        || (typeof field === 'object' ? field?.label : '') || key || '';
}

export function nativeSigningFieldHelp(language, key) {
    return fieldHelpKeys[key] ? nativeSigningText(language, fieldHelpKeys[key]) : '';
}
